    public function test_the_queue_is_paginated_and_does_not_query_per_ticket(): void
    {
        foreach (range(1, 30) as $_) {
            $this->ticket(['assigned_to' => $this->support->id]);
        }
        $queries = 0;
        DB::listen(function () use (&$queries) {
            $queries++;
        });

        $this->actingAs($this->support)->get('/admin/support-tickets')->assertInertia(fn (Assert $page) => $page
            ->where('tickets.total', 30)->has('tickets.data', config('taxikosmos.admin.per_page_options')[0])->where('tickets.last_page', (int) ceil(30 / config('taxikosmos.admin.per_page_options')[0])));

        $this->assertLessThan(25, $queries, 'a constant number of queries, not one per ticket');
        $this->actingAs($this->support)->get('/admin/support-tickets?page=2')->assertInertia(fn (Assert $page) => $page->where('tickets.current_page', 2));
    }

    // ---- permissions -----------------------------------------------------------------------------------------------------

    /** @return list<array{string, string, array<string, mixed>}> */
    private function writeRoutes(SupportTicket $ticket): array
    {
        return [['get', '/admin/support-tickets', []], ['get', "/admin/support-tickets/{$ticket->id}", []], ['post', "/admin/support-tickets/{$ticket->id}/assign", ['assignee_id' => null]],
            ['post', "/admin/support-tickets/{$ticket->id}/messages", ['body' => 'x']], ['post', "/admin/support-tickets/{$ticket->id}/resolve", ['resolution' => 'x']], ['post', "/admin/support-tickets/{$ticket->id}/reopen", []]];
    }

    public function test_every_route_needs_support_manage(): void
    {
        $ticket = $this->ticket();

        foreach ($this->writeRoutes($ticket) as [$method, $url, $body]) {
            foreach ([AdminRole::Finance, AdminRole::Dispatcher] as $role) {
                $this->actingAs($this->admin($role))->{$method.'Json'}($url, $body)->assertForbidden();
            }
        }

        $fresh = $ticket->fresh();
        $this->assertSame([SupportStatus::Open, null, null], [$fresh->status, $fresh->assigned_to, $fresh->resolution]);
        $this->assertSame(1, SupportTicketMessage::query()->count());
        $this->assertSame(0, ActivityLogEntry::query()->where('description', 'like', 'support_ticket.%')->count());
    }

    public function test_a_guest_is_sent_to_login_on_every_route(): void
    {
        $ticket = $this->ticket();

        foreach ($this->writeRoutes($ticket) as [$method, $url, $body]) {
            $this->{$method}($url, $body)->assertRedirect('/login');
        }

        $this->assertSame(SupportStatus::Open, $ticket->fresh()->status);
        $this->assertSame(0, ActivityLogEntry::query()->where('description', 'like', 'support_ticket.%')->count());
    }

    // ---- assign ----------------------------------------------------------------------------------------------------------

    public function test_assigning_sets_the_assignee_starts_the_work_audits_it_and_publishes_after_commit(): void
    {
        Event::fake([SupportTicketUpdated::class]);
        $ticket = $this->ticket();
        $colleague = $this->admin(AdminRole::Admin, ['name' => 'Colleague']);

        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/assign", ['assignee_id' => $colleague->id])->assertRedirect()->assertSessionHas('success', 'Ticket assigned.');

        $fresh = $ticket->fresh();
        $this->assertSame([$colleague->id, SupportStatus::InProgress], [$fresh->assigned_to, $fresh->status]);
        $entry = $this->entries('support_ticket.assigned')->sole();
        $this->assertSame([$this->support->id, $ticket->id], [$entry->causer_id, $entry->subject_id]);
        $this->assertSame(['assigned_to' => null, 'status' => 'open'], $entry->attribute_changes['old']);
        $this->assertSame(['assigned_to' => $colleague->id, 'status' => 'in_progress'], $entry->attribute_changes['attributes']);
        Event::assertDispatched(SupportTicketUpdated::class, fn ($e) => $e->ticketId === $ticket->id && $e->change === 'assignment' && $e->status === 'in_progress' && $e->requesterUserId === $ticket->requester_id);
    }

    public function test_assigning_to_nobody_takes_the_assignee_off_and_the_same_assignee_again_changes_nothing(): void
    {
        $ticket = $this->ticket(['assigned_to' => $this->support->id, 'status' => SupportStatus::InProgress]);

        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/assign", ['assignee_id' => $this->support->id])->assertSessionHas('success', 'Nothing to change.');
        $this->assertCount(0, $this->entries('support_ticket.assigned'));

        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/assign", ['assignee_id' => null])->assertRedirect();
        $this->assertNull($ticket->fresh()->assigned_to);
        $this->assertCount(1, $this->entries('support_ticket.assigned'));
    }

    public function test_only_active_admins_who_handle_support_can_be_assigned(): void
    {
        $ticket = $this->ticket();
        $finance = $this->admin(AdminRole::Finance);
        $suspended = $this->admin(AdminRole::Support);
        $suspended->forceFill(['status' => 'suspended'])->save();
        $rider = User::factory()->rider()->create();

        foreach ([$finance->id, $suspended->id, $rider->id, 99999999] as $assignee) {
