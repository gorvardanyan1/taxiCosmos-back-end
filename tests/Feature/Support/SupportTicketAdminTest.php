    }

    // ---- resolve and reopen ----------------------------------------------------------------------------------------------

    public function test_resolving_needs_a_resolution_and_records_it_the_time_the_audit_and_the_event(): void
    {
        Event::fake([SupportTicketUpdated::class]);
        $this->travelTo('2026-10-15 09:00:00');
        $ticket = $this->ticket();

        foreach (['', '   ', null] as $empty) {
            $this->actingAs($this->support)->postJson("/admin/support-tickets/{$ticket->id}/resolve", ['resolution' => $empty])->assertUnprocessable()->assertJsonValidationErrors(['resolution']);
        }
        $this->assertSame(SupportStatus::Open, $ticket->fresh()->status);
        $this->assertCount(0, $this->entries('support_ticket.resolved'));

        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/resolve", ['resolution' => '  Refunded the difference.  '])->assertRedirect()->assertSessionHas('success', 'Ticket resolved.');

        $fresh = $ticket->fresh();
        $this->assertSame([SupportStatus::Resolved, 'Refunded the difference.', '2026-10-15 09:00:00', $this->support->id], [$fresh->status, $fresh->resolution, $fresh->resolved_at->format('Y-m-d H:i:s'), $fresh->assigned_to]);
        $entry = $this->entries('support_ticket.resolved')->sole();
        $this->assertSame([$this->support->id, $ticket->id, 'Refunded the difference.'], [$entry->causer_id, $entry->subject_id, $entry->properties['reason']]);
        Event::assertDispatched(SupportTicketUpdated::class, fn ($e) => $e->change === 'status' && $e->status === 'resolved');
    }

    public function test_resolving_twice_is_a_conflict_and_happens_once(): void
    {
        $ticket = $this->ticket();
        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/resolve", ['resolution' => 'First.'])->assertRedirect();

        $this->actingAs($this->admin(AdminRole::Admin))->postJson("/admin/support-tickets/{$ticket->id}/resolve", ['resolution' => 'Second.'])->assertStatus(409);

        $this->assertSame('First.', $ticket->fresh()->resolution);
        $this->assertCount(1, $this->entries('support_ticket.resolved'));
    }

    public function test_reopening_clears_the_resolution_and_only_a_finished_ticket_can_be_reopened(): void
    {
        Event::fake([SupportTicketUpdated::class]);
        $resolved = $this->ticket(['status' => SupportStatus::Resolved, 'resolved_at' => now(), 'resolution' => 'Done.']);
        $closed = $this->ticket(['status' => SupportStatus::Closed, 'resolved_at' => now(), 'resolution' => 'Done.']);
        $open = $this->ticket();

        $this->actingAs($this->support)->post("/admin/support-tickets/{$resolved->id}/reopen")->assertRedirect()->assertSessionHas('success', 'Ticket reopened.');
        $this->actingAs($this->support)->post("/admin/support-tickets/{$closed->id}/reopen")->assertRedirect();
        $this->actingAs($this->support)->postJson("/admin/support-tickets/{$open->id}/reopen")->assertStatus(409);

        $fresh = $resolved->fresh();
        $this->assertSame([SupportStatus::Open, null, null], [$fresh->status, $fresh->resolved_at, $fresh->resolution]);
        $this->assertSame(SupportStatus::Open, $closed->fresh()->status);
        $this->assertCount(2, $this->entries('support_ticket.reopened'));
        Event::assertDispatchedTimes(SupportTicketUpdated::class, 2);
        // Staff can reply again once it is open.
        $this->actingAs($this->support)->post("/admin/support-tickets/{$resolved->id}/messages", ['body' => 'Back on it.'])->assertRedirect();
    }

    public function test_an_unknown_ticket_is_a_404_on_every_action(): void
    {
        foreach ([['assign', ['assignee_id' => null]], ['messages', ['body' => 'x']], ['resolve', ['resolution' => 'x']], ['reopen', []]] as [$action, $body]) {
            $this->actingAs($this->support)->postJson("/admin/support-tickets/999999/{$action}", $body)->assertNotFound();
        }
    }

    public function test_the_events_are_published_only_after_the_transaction_commits(): void
    {
        Event::fake([SupportTicketUpdated::class]);
        $ticket = $this->ticket();

        try {
            DB::transaction(function () use ($ticket) {
                app(SupportTicketService::class)->resolve($this->support, $ticket, 'Will be rolled back.');
                throw new \RuntimeException('boom');
            });
        } catch (\RuntimeException) {
        }

        $this->assertSame(SupportStatus::Open, $ticket->fresh()->status);
        Event::assertNotDispatched(SupportTicketUpdated::class);
    }

