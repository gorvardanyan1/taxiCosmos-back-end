    public function test_an_internal_note_is_staff_only_changes_no_status_and_publishes_nothing(): void
    {
        Event::fake([SupportTicketUpdated::class]);
        $ticket = $this->ticket(['last_message_at' => now()->subHour()]);
        $before = $ticket->fresh();

        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/messages", ['body' => 'Driver has history.', 'internal' => true])->assertRedirect()->assertSessionHas('success', 'Internal note added.');

        $note = SupportTicketMessage::query()->where('body', 'Driver has history.')->sole();
        $this->assertTrue($note->is_internal_note);
        $fresh = $ticket->fresh();
        $this->assertSame([$before->status, $before->assigned_to, $before->last_message_at->timestamp], [$fresh->status, $fresh->assigned_to, $fresh->last_message_at->timestamp]);
        Event::assertNotDispatched(SupportTicketUpdated::class);
        $this->assertCount(1, $this->entries('support_ticket.note_added'));
    }

    public function test_a_message_needs_text_and_cannot_be_added_to_a_resolved_ticket(): void
    {
        $open = $this->ticket();
        $resolved = $this->ticket(['status' => SupportStatus::Resolved]);

        $this->actingAs($this->support)->postJson("/admin/support-tickets/{$open->id}/messages", ['body' => ''])->assertUnprocessable()->assertJsonValidationErrors(['body']);
