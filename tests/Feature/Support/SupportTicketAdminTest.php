    // ---- reply and internal note -----------------------------------------------------------------------------------------

    public function test_a_reply_is_saved_asks_the_requester_claims_the_ticket_audits_without_the_text_and_publishes_for_a_push(): void
    {
        Event::fake([SupportTicketUpdated::class]);
        $ticket = $this->ticket();

        $this->actingAs($this->support)->post("/admin/support-tickets/{$ticket->id}/messages", ['body' => 'We are on it.'])->assertRedirect()->assertSessionHas('success', 'Reply sent.');

        $message = SupportTicketMessage::query()->where('body', 'We are on it.')->sole();
        $this->assertSame([$ticket->id, $this->support->id, false], [$message->ticket_id, $message->author_id, $message->is_internal_note]);
        $fresh = $ticket->fresh();
        $this->assertSame([SupportStatus::WaitingOnCustomer, $this->support->id], [$fresh->status, $fresh->assigned_to]);
        $entry = $this->entries('support_ticket.replied')->sole();
        $this->assertSame($this->support->id, $entry->causer_id);
        $this->assertStringNotContainsString('We are on it.', json_encode([$entry->properties, $entry->attribute_changes]));
        Event::assertDispatched(SupportTicketUpdated::class, fn ($e) => $e->change === 'reply' && $e->status === 'waiting_on_customer' && $e->requesterUserId === $ticket->requester_id);
    }

