{
    private User $support;

    protected function setUp(): void
    {
        parent::setUp();

        $this->support = $this->admin(AdminRole::Support, ['name' => 'Sam Support']);
    }

    private function ticket(array $state = [], ?User $requester = null): SupportTicket
    {
        $requester ??= User::factory()->rider()->create(['name' => 'Ana Rider']);
        $ticket = SupportTicket::factory()->create(array_merge(['requester_id' => $requester->id], $state));
        SupportTicketMessage::factory()->create(['ticket_id' => $ticket->id, 'author_id' => $requester->id, 'body' => 'Please help.']);

        // The code is generated by the database from the id.
        return $ticket->refresh();
    }

    private function entries(string $action)
    {
        return ActivityLogEntry::query()->where('description', $action)->get();
    }

    // ---- list, filters, detail -------------------------------------------------------------------------------------------

    public function test_the_page_lists_tickets_with_the_selected_conversation_internal_notes_and_the_linked_trip(): void
    {
        $trip = Trip::factory()->matched()->create();
        $ticket = $this->ticket(['subject' => 'Overcharged', 'category' => SupportCategory::Fare, 'trip_id' => $trip->id, 'assigned_to' => $this->support->id]);
        SupportTicketMessage::factory()->create(['ticket_id' => $ticket->id, 'author_id' => $this->support->id, 'body' => 'Looking.']);
        SupportTicketMessage::factory()->create(['ticket_id' => $ticket->id, 'author_id' => $this->support->id, 'body' => 'Meter checked.', 'is_internal_note' => true]);

        $this->actingAs($this->support)->get('/admin/support-tickets')->assertInertia(fn (Assert $page) => $page
            ->component('SupportTickets/Index')
            ->where('tickets.total', 1)
            ->where('tickets.data.0.code', $ticket->code)
            ->where('tickets.data.0.requester', ['name' => 'Ana Rider', 'type' => 'rider', 'code' => sprintf('R-%05d', $ticket->requester_id)])
            ->where('tickets.data.0.assignee', ['id' => $this->support->id, 'name' => 'Sam Support'])
            ->where('selected.id', $ticket->id)
            ->where('selected.messages.0.kind', 'requester')
            ->where('selected.messages.1', fn ($m) => $m['kind'] === 'staff' && $m['body'] === 'Looking.' && $m['author'] === 'Sam Support')
            ->where('selected.messages.2.kind', 'internal')
            ->where('selected.linked_trip', ['id' => $trip->id, 'code' => $trip->public_code])
            ->where('assignees', [['id' => $this->support->id, 'name' => 'Sam Support']])
            ->where('me', $this->support->id)
            ->where('actions.refund', null)
            ->where('actions.adjustFare', null)
            ->where('actions.resolve', '/admin/support-tickets/{id}/resolve'));
    }

    public function test_a_driver_requester_shows_their_driver_code(): void
    {
        $driver = User::factory()->driver()->create();
        $profile = DriverProfile::factory()->create(['user_id' => $driver->id]);
        $this->ticket(['requester_type' => AppClient::Driver], $driver);

        $this->actingAs($this->support)->get('/admin/support-tickets')->assertInertia(fn (Assert $page) => $page
            ->where('tickets.data.0.requester.type', 'driver')->where('tickets.data.0.requester.code', sprintf('D-%04d', $profile->id)));
    }

    public function test_the_queue_is_newest_activity_first_and_the_ticket_param_and_show_route_pick_the_selection(): void
    {
        $old = $this->ticket(['last_message_at' => now()->subDay()]);
        $new = $this->ticket(['last_message_at' => now()]);

        $this->actingAs($this->support)->get('/admin/support-tickets')->assertInertia(fn (Assert $page) => $page
            ->where('tickets.data.0.id', $new->id)->where('tickets.data.1.id', $old->id)->where('selected.id', $new->id));
        $this->actingAs($this->support)->get("/admin/support-tickets?ticket={$old->id}")->assertInertia(fn (Assert $page) => $page->where('selected.id', $old->id));
        $this->actingAs($this->support)->get("/admin/support-tickets/{$old->id}")->assertInertia(fn (Assert $page) => $page->component('SupportTickets/Index')->where('selected.id', $old->id)->where('tickets.total', 2));
        $this->actingAs($this->support)->get('/admin/support-tickets/999999')->assertNotFound();
        // An unknown id in ?ticket= falls back to the first ticket of the page.
        $this->actingAs($this->support)->get('/admin/support-tickets?ticket=999999')->assertInertia(fn (Assert $page) => $page->where('selected.id', $new->id));
    }

    public function test_the_filters_narrow_the_queue_and_the_url_state_is_echoed(): void
    {
        $other = $this->admin(AdminRole::Admin);
        $a = $this->ticket(['subject' => 'Lost my phone', 'category' => SupportCategory::LostItem, 'priority' => SupportPriority::High, 'status' => SupportStatus::InProgress, 'assigned_to' => $this->support->id]);
        $b = $this->ticket(['subject' => 'Rude driver', 'category' => SupportCategory::DriverBehavior, 'status' => SupportStatus::Open]);
        $c = $this->ticket(['subject' => 'Wrong fare', 'category' => SupportCategory::Fare, 'status' => SupportStatus::Resolved, 'assigned_to' => $other->id], User::factory()->rider()->create(['name' => 'Zed Special']));
        $ids = fn (string $query) => $this->actingAs($this->support)->get("/admin/support-tickets?{$query}")->original->getData()['page']['props']['tickets']['data'];
        $pluck = fn (string $query) => array_column($ids($query), 'id');

        $this->assertEqualsCanonicalizing([$a->id], $pluck('filter[status]=in_progress'));
        $this->assertEqualsCanonicalizing([$b->id], $pluck('filter[category]=driver_behavior'));
        $this->assertEqualsCanonicalizing([$a->id], $pluck('filter[priority]=high'));
        $this->assertEqualsCanonicalizing([$a->id], $pluck('filter[assignee]=me'));
        $this->assertEqualsCanonicalizing([$b->id], $pluck('filter[assignee]=unassigned'));
        $this->assertEqualsCanonicalizing([$c->id], $pluck("filter[assignee]={$other->id}"));
        $this->assertEqualsCanonicalizing([$c->id], $pluck('filter[search]=Zed'), 'by requester name');
        $this->assertEqualsCanonicalizing([$b->id], $pluck('filter[search]=rude'), 'by subject');
        $this->assertEqualsCanonicalizing([$a->id], $pluck("filter[search]={$a->code}"), 'by code');
        $this->assertEqualsCanonicalizing([$a->id], $pluck("filter[search]={$a->id}"), 'by number');
        $this->assertEqualsCanonicalizing([$a->id], $pluck('filter[status]=in_progress&filter[category]=lost_item&filter[assignee]=me'), 'combined');
        $this->assertSame([], $pluck('filter[status]=closed'));

        $this->actingAs($this->support)->get('/admin/support-tickets?filter[status]=resolved')->assertInertia(fn (Assert $page) => $page->where('filters', ['status' => 'resolved']));
    }

